// and misses trip-caused drops, under-counting bottleneck episodes.
export { onInventoryChange };

// v0.0.9.6.9.12 — per-pkg skip dedupe. Returns true if we should emit
// pickup.failed for this pkg in the current cargo state, and marks it
// so subsequent ticks at the same cargo state are silent. Set is
// cleared by onInventoryChange when cargo shifts; caller should use
// a stable identifier (worldCell index for ring pkgs, cell key for
// interior pkgs) so the same pkg is recognized tick-to-tick.
function shouldEmitSkipFor(pkgKey) {
  if (!S._transient.skipEmittedPkgs) S._transient.skipEmittedPkgs = new Set();
  if (S._transient.skipEmittedPkgs.has(pkgKey)) return false;
  S._transient.skipEmittedPkgs.add(pkgKey);
  return true;
}

// v0.0.9.4.1 — shared tooltip formatter for pkg hover. Keeps the
// fieldstrip (ground pkgs) and cargo grid (carried pkgs) tooltips in
// lockstep. Multi-line (CSS `white-space: pre` on `.has-tooltip::after`
// renders the `\n` breaks). Format:
//   [size] label (modifier)
//   [recovery from PTR-XXXX]  |  [lost]         (if applicable)
//   → destination
//   Xc
export function formatPkgTooltip(pkg) {
  const modTag = pkg.modifier ? ` (${pkg.modifier})` : '';
  const lines = [`[${pkg.size}] ${pkg.label}${modTag}`];
  if (pkg.isRecovery && pkg.recoveryFromPorter) {
    lines.push(`[recovery from ${shortPorterId(pkg.recoveryFromPorter)}]`);
  } else if (pkg.isLost) {
    lines.push(`[lost]`);
  }
  lines.push(`\u2192 ${getDisplayLabel(pkg.destId)}`);
  lines.push(`${pkg.scrip}\u00a2`);
  return lines.join('\n');
}

// v0.0.9.6.9.26 — HTML tooltip formatter for the cargo grid. Same
// content as formatPkgTooltip but emits styled HTML so damaged pkgs
// can show "13¢ (was 22¢)" with the current value in pink and the
// original dimmed. Used by the rich-tooltip path in render/hud.js;
// fieldstrip stays on the plain-text formatter (its pkgs are pristine).
function esc(s) {
  return String(s).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}
export function formatPkgTooltipHTML(pkg) {
  const modTag = pkg.modifier ? ` (${esc(pkg.modifier)})` : '';
  const lines = [`<div>[${esc(pkg.size)}] ${esc(pkg.label)}${modTag}</div>`];
  if (pkg.isRecovery && pkg.recoveryFromPorter) {
    lines.push(`<div>[recovery from ${esc(shortPorterId(pkg.recoveryFromPorter))}]</div>`);
  } else if (pkg.isLost) {
    lines.push(`<div>[lost]</div>`);
  }
  lines.push(`<div>\u2192 ${esc(getDisplayLabel(pkg.destId))}</div>`);
  // Damaged: current scrip in pink, "(was X¢)" dimmed. Undamaged or
  // missing scripBase: just show current value.
  const damaged = pkg.damaged && typeof pkg.scripBase === 'number' && pkg.scripBase > pkg.scrip;
  if (damaged) {
    lines.push(`<div><span class="rich-tip-hot">${pkg.scrip}\u00a2</span> <span class="rich-tip-dim">(was ${pkg.scripBase}\u00a2)</span></div>`);
  } else {
    lines.push(`<div>${pkg.scrip}\u00a2</div>`);
  }
  return lines.join('');
}

// v0.0.9.4.1 — exported for the cursor-pickup path in world.js's
// fieldstrip click handler so both auto and manual pickup compute
// the same reach.
// Base C.PKG_PICKUP_RANGE when bare-handed; extended to
// C.STICKY_GUN_RANGE when gun is owned and has ammo. Holstering
// does NOT extend range — you can't shoot through the holster.
export function pickupRange() {
  let range;
  if (S.stickyGun && !S.stickyGun.holstered && S.stickyGun.ammo > 0) {
    range = C.STICKY_GUN_RANGE;
  } else {
    range = C.PKG_PICKUP_RANGE;
  }
  // v0.0.8 — downpour reduces visibility/reach
  if (weatherAtCourier().intensity === 'downpour') {
    range = Math.max(2, range - C.DOWNPOUR_RANGE_PENALTY);
  }
  return range;
}

